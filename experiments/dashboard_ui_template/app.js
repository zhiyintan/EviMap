async function ensureDocBundle(docId) {
  // Sharded deploy: fetch only the bucket holding this doc's text + phrases.
  // Legacy (monolithic) deploy: data is already eager-loaded, nothing to do.
  if (!state.sharded || state.docs.has(docId)) return;
  const bucket = state.docIndex[docId];
  if (bucket === undefined || bucket === null) return;
  const pad = String(bucket).padStart(4, "0");
  const [docs, phs] = await Promise.all([
    loadJsonl(`data/docbuckets/doc_${pad}.jsonl`).catch(() => []),
    loadJsonl(`data/phrasebuckets/ph_${pad}.jsonl`).catch(() => []),
  ]);
  for (const d of docs) state.docs.set(d.doc_id, d);
  for (const r of phs) if (!state.docAllPhrases.has(r.doc_id)) state.docAllPhrases.set(r.doc_id, r.phrases);
}

async function ensureTopicPhrases(atomId) {
  // Sharded deploy: fetch the topic-phrase shard holding this atom, so the
  // doc list can show per-doc phrase counts and filter by related phrase.
  if (!state.sharded || state.topicPhrases.has(atomId)) return;
  const members = state.virtualTopicMembers?.get(atomId);
  if (members && members.length) {
    await Promise.all(members.map(memberId => ensureTopicPhrases(memberId)));
    const merged = new Map();
    for (const memberId of members) {
      const memberMap = state.topicPhrases.get(memberId);
      if (!memberMap) continue;
      for (const [docId, texts] of memberMap.entries()) {
        const arr = merged.get(docId) || [];
        const seen = new Set(arr);
        for (const text of (texts || [])) {
          if (!seen.has(text)) {
            seen.add(text);
            arr.push(text);
          }
        }
        merged.set(docId, arr);
      }
    }
    state.topicPhrases.set(atomId, merged);
    return;
  }
  const bucket = state.topicPhraseIndex[atomId];
  if (bucket === undefined || bucket === null) { state.topicPhrases.set(atomId, new Map()); return; }
  const pad = String(bucket).padStart(4, "0");
  const rows = await loadJsonl(`data/topicphrases/tp_${pad}.jsonl`).catch(() => []);
  const byAtom = new Map();
  for (const r of rows) {
    let m = byAtom.get(r.atom_id);
    if (!m) { m = new Map(); byAtom.set(r.atom_id, m); }
    m.set(r.doc_id, r.texts || []);
  }
  if (!byAtom.has(atomId)) byAtom.set(atomId, new Map());
  for (const [aid, m] of byAtom) if (!state.topicPhrases.has(aid)) state.topicPhrases.set(aid, m);
}

function escapeHtml(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

// Fold the many per-atom other_has_meaning / other_no_meaning nodes into one
// synthetic topic each, and rewrite every aspect's member list (and flat tree)
// to point at those two. Display-only collapse; called once at load.
function collapseOtherBins(nodes, aspects) {
  const OTHER_KINDS = ["other_has_meaning", "other_no_meaning"];
  const byKind = new Map();  // kind -> array of nodes
  for (const n of nodes) {
    const k = n.basket_kind;
    if (OTHER_KINDS.includes(k)) {
      if (!byKind.has(k)) byKind.set(k, []);
      byKind.get(k).push(n);
    }
  }
  if (!byKind.size) return;

  const oldIdToSynthetic = new Map();  // old atom_id -> synthetic atom_id
  state.otherIdRemap = oldIdToSynthetic;  // used when matching occurrences by atom_id
  const syntheticIds = new Set();
  for (const kind of OTHER_KINDS) {
    const group = byKind.get(kind);
    if (!group || !group.length) continue;
    const synthId = "other::" + kind;
    syntheticIds.add(synthId);
    const docIds = new Set();
    const reps = [];
    let entryIds = [];
    for (const n of group) {
      oldIdToSynthetic.set(n.atom_id, synthId);
      for (const d of (n.support_doc_ids || [])) docIds.add(d);
      for (const p of (n.representative_phrases || [])) {
        if (reps.length < 12 && !reps.includes(p)) reps.push(p);
      }
      entryIds = entryIds.concat(n.member_phrase_entry_ids || n.member_phrase_type_ids || []);
    }
    const synthetic = {
      atom_id: synthId,
      display_title: group[0].display_title,  // "Other — Has Meaning" / "— No Clear Meaning"
      basket_kind: kind,
      basket_display_name: group[0].basket_display_name,
      description: group[0].description || "",
      is_pending_review: !!group[0].is_pending_review,
      representative_phrases: reps,
      support_doc_ids: Array.from(docIds),
      support_doc_count: docIds.size,
      member_phrase_entry_ids: entryIds,
      member_phrase_type_ids: entryIds,
      n_member_entries: entryIds.length,
      _collapsed_from: group.length,
    };
    state.topicById.set(synthId, synthetic);
    console.log(`[collapseOtherBins] ${kind}: folded ${group.length} nodes -> 1 (${docIds.size} docs)`);
  }

  // Rewrite aspect member lists + flat tree to use the two synthetic ids.
  for (const a of aspects) {
    const members = a.member_atom_ids || [];
    if (!members.some(id => oldIdToSynthetic.has(id))) continue;
    const seen = new Set();
    const next = [];
    for (const id of members) {
      const repl = oldIdToSynthetic.get(id) || id;
      if (seen.has(repl)) continue;
      seen.add(repl);
      next.push(repl);
    }
    a.member_atom_ids = next;
    a.n_atoms = next.length;
    // Rebuild the tree so the synthetic Other nodes render as plain top-level
    // rows. Some aspects have real parent/child edges (n_edges>0) where Other
    // nodes hang under a parent; remapping only roots would leave the rest
    // dangling, so we drop every Other id out of the hierarchy and re-add the
    // (deduped) synthetic ids as roots.
    if (a.tree) {
      const isOtherOld = (id) => oldIdToSynthetic.has(id);
      const cbp = a.tree.children_by_parent || {};
      const newCbp = {};
      for (const [parent, kids] of Object.entries(cbp)) {
        if (isOtherOld(parent)) continue;  // an Other node is never a parent
        const keptKids = (kids || []).filter(k => !isOtherOld(k));
        if (keptKids.length) newCbp[parent] = keptKids;
      }
      a.tree.children_by_parent = newCbp;
      if (Array.isArray(a.tree.edges)) {
        a.tree.edges = a.tree.edges.filter(
          e => !isOtherOld(e[0]) && !isOtherOld(e[1])
        );
        a.tree.n_edges = a.tree.edges.length;
      }
      // roots = old non-Other roots (minus any now-childless) + synthetic ids
      const rseen = new Set();
      const roots = [];
      for (const id of (a.tree.roots || [])) {
        if (isOtherOld(id) || rseen.has(id)) continue;
        rseen.add(id); roots.push(id);
      }
      for (const sid of next) {
        if (syntheticIds.has(sid) && !rseen.has(sid)) { rseen.add(sid); roots.push(sid); }
      }
      a.tree.roots = roots;
    }
  }
}

// Display-only merge of the two bottom "Other" top-level aspects into a single
// "Other" aspect with two mid-level groups. The pipeline emits two separate
// Other aspects:
//   1. source='coassociation_3layer' / aspect_key='others' — isolated but
//      meaningful mid-groups that the top-level clustering could not place and
//      that were too small to stand alone. Its tree is already a 2-level
//      group-header → topic structure.
//   2. source='absorb_small_atoms' / aspect_key='other_small' — the recycled
//      bin of thinly-supported atoms (<1% docs). Its tree is flat.
// Showing them as two separate top-level "Other" entries is confusing, so we
// fold both under one "Other" aspect, each becoming a labelled mid-level group:
//   coassociation 'others'   -> "Distinct but unclustered"
//   absorb 'other_small'     -> "Minor & scattered"
// Underlying nodes/occurrences are untouched; we only rebuild the aspects array
// and synthesise two mid-level group-header nodes so renderAspectTree() can show
// them as collapsible folders. Must run AFTER collapseOtherBins (it operates on
// that function's output) and BEFORE state.aspects/aspectById are finalised.
function mergeOtherAspects(nodes, aspects) {
  // Identify the two Other aspects by source (preferred) / aspect_key, never by
  // the numeric aspect-13 id (it differs per domain).
  const isDistinct = (a) =>
    a.source === "coassociation_3layer" && a.aspect_key === "others";
  const isScattered = (a) =>
    a.source === "absorb_small_atoms" || a.aspect_key === "other_small";

  const distinctAspect = aspects.find(isDistinct) || null;
  const scatteredAspect = aspects.find(isScattered) || null;

  // Need at least two to merge; 0 or 1 -> no merge. But for naming consistency
  // across domains, a lone bottom "Other" still shows as plain "Other" (some
  // domains only produce the scattered bin, e.g. eu_debates), so every domain's
  // last category reads the same.
  const present = [distinctAspect, scatteredAspect].filter(Boolean);
  if (present.length < 2) {
    for (const a of present) a.aspect_title = "Other";
    return;
  }

  // Build one synthetic mid-level group-header node per source Other. It mirrors
  // the real coassociation group-header shape (basket_kind/is_group_header) so
  // renderAspectTree() treats it as a collapsible folder, not a doc-opening leaf.
  function makeMidHeader(headerId, title, srcAspect) {
    const docIds = new Set();
    let memberAtoms = 0;
    for (const mid of (srcAspect.member_atom_ids || [])) {
      const t = state.topicById.get(mid);
      memberAtoms++;
      for (const d of (t?.support_doc_ids || [])) docIds.add(d);
    }
    const header = {
      atom_id: headerId,
      display_title: title,
      centroid_title: title,
      basket_kind: "group_header",
      is_group_header: true,
      n_member_entries: memberAtoms,
      representative_phrases: [],
      support_doc_count: docIds.size,
      support_doc_ids: Array.from(docIds),
      member_phrase_entry_ids: [],
    };
    state.topicById.set(headerId, header);
    return { header, docIds };
  }

  const MID_DISTINCT_ID = "group::other-distinct";
  const MID_SCATTERED_ID = "group::other-scattered";

  // children_by_parent for the merged aspect: the two mid headers each point to
  // their source aspect's roots; then we carry over every deeper edge from the
  // distinct aspect's tree (its roots are themselves group headers with their
  // own children) so the full sub-structure survives.
  const childrenByParent = {};
  const mergedMembers = [];
  const roots = [];
  let docTotal = 0;

  // Each source Other becomes a mid-level folder only when the folder earns its
  // row. Other-recovery can move every topic out of a bin, leaving a folder over
  // nothing; and a folder over exactly ONE topic is pure indirection — two rows
  // carrying the same count, neither telling you anything the other did not.
  const allDocs = new Set();
  function addSection(headerId, title, srcAspect, children, deeperEdges) {
    for (const [parent, kids] of Object.entries(deeperEdges || {})) {
      childrenByParent[parent] = (kids || []).slice();
    }
    if (!children.length) return;
    if (children.length === 1) {
      roots.push(children[0]);
      mergedMembers.push(children[0]);
      for (const d of (state.topicById.get(children[0])?.support_doc_ids || [])) {
        allDocs.add(d);
      }
      return;
    }
    const { docIds } = makeMidHeader(headerId, title, srcAspect);
    childrenByParent[headerId] = children;
    roots.push(headerId);
    mergedMembers.push(headerId, ...children);
    for (const d of docIds) allDocs.add(d);
  }

  // 1) "Distinct but unclustered" (from coassociation 'others'). Its roots are
  //    themselves group headers with topic children, so carry their edges over.
  const distinctTree = distinctAspect.tree || {};
  addSection(MID_DISTINCT_ID, "Distinct but unclustered", distinctAspect,
             (distinctTree.roots || distinctAspect.member_atom_ids || []).slice(),
             distinctTree.children_by_parent);

  // 2) "Minor & scattered" (from absorb_small_atoms 'other_small').
  addSection(MID_SCATTERED_ID, "Minor & scattered", scatteredAspect,
             (scatteredAspect.member_atom_ids || []).slice(), null);

  // union, not sum: a document can support topics in both bins
  docTotal = allDocs.size;

  // edges array kept consistent with the on-disk {parent, child} object form
  // (renderAspectTree only reads roots + children_by_parent, but other code and
  // future readers expect edges to mirror children_by_parent).
  const edges = [];
  for (const [parent, kids] of Object.entries(childrenByParent)) {
    for (const child of kids) edges.push({ parent, child });
  }

  const merged = {
    // aspect_id chosen so localeCompare keeps it last (after aspect-NN and any
    // other aspect-zzz-* bins).
    aspect_id: "aspect-zzz-other-merged",
    aspect_key: "other_merged",
    aspect_title: "Other",
    aspect_name_warning:
      "Display-only merge of the unclustered-but-distinct and " +
      "minor/scattered Other bins.",
    n_atoms: mergedMembers.length,
    n_documents_total: docTotal,
    member_atom_ids: mergedMembers,
    tree: {
      roots,
      edges,
      children_by_parent: childrenByParent,
      n_edges: edges.length,
      is_flat: false,
    },
    source: "other_merged_display",
  };

  // Replace the two source Other aspects with the single merged one, in place.
  const next = [];
  let inserted = false;
  for (const a of aspects) {
    if (a === distinctAspect || a === scatteredAspect) {
      if (!inserted) { next.push(merged); inserted = true; }
      continue;
    }
    next.push(a);
  }
  aspects.length = 0;
  for (const a of next) aspects.push(a);
}

