// --- initial-load progress bar (counts fetched files/parts) ---
let loadTracking = false, loadDone = 0, loadTotal = 0;
let deferredDataPromise = null;
function renderLoadBar() {
  const pct = loadTotal ? Math.min(100, Math.round(loadDone / loadTotal * 100)) : 0;
  const fill = document.getElementById("loading-fill");
  if (fill) fill.style.width = pct + "%";
  const label = document.getElementById("loading-label");
  if (label) label.textContent = `Loading catalogue index… ${pct}%`;
}

// ============================================================ //
function yieldToBrowser() {
  return new Promise(resolve => window.setTimeout(resolve, 0));
}

async function appendJsonl(text, out) {
  let start = 0;
  let parsed = 0;
  let lastYield = performance.now();
  while (start < text.length) {
    let end = text.indexOf("\n", start);
    if (end === -1) end = text.length;
    const line = text.slice(start, end).trim();
    if (line) out.push(JSON.parse(line));
    start = end + 1;
    parsed += 1;
    if (parsed % 1000 === 0 && performance.now() - lastYield > 12) {
      await yieldToBrowser();
      lastYield = performance.now();
    }
  }
}

async function loadJsonl(path) {
  // bust browser cache; data files are regenerated by experiments.
  // Manifest-aware: a logical file may be split into numbered parts.
  const name = path.replace(/^data\//, "");
  const parts = (state.manifest && state.manifest[name]) || null;
  const paths = parts ? parts.map(p => "data/" + p) : [path];
  // Fetch all parts CONCURRENTLY (HTTP/2 multiplexes). Sequential awaits here
  // turned an 11-part nodes file into a ~5s critical chain (each part waiting
  // for the previous). Promise.all keeps array order, so concat stays correct.
  const textPromises = paths.map(async (pth) => {
    try {
      const r = await fetch(pth + "?t=" + Date.now(), { cache: "no-store" });
      if (!r.ok) throw new Error(`fetch ${pth}: ${r.status}`);
      return await r.text();
    } finally {
      if (loadTracking) { loadDone++; renderLoadBar(); }
    }
  });
  const out = [];
  for (const textPromise of textPromises) {
    await appendJsonl(await textPromise, out);
  }
  return out;
}

async function loadJson(path) {
  try {
    const r = await fetch(path + "?t=" + Date.now(), { cache: "no-store" });
    if (!r.ok) throw new Error(`fetch ${path}: ${r.status}`);
    return await r.json();
  } finally {
    if (loadTracking) { loadDone++; renderLoadBar(); }
  }
}

function domainDisplayName(domain) {
  const known = {
    city_hotel: "City Hotel Catalogue",
    peer_review: "Peer Review Catalogue",
    career_jobs: "Career Jobs Catalogue",
    music_reviews: "Music Review Catalogue",
  };
  if (known[domain]) return known[domain];
  return String(domain || "Catalogue")
    .split(/[_-]+/)
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ") + " Catalogue";
}

function applyCatalogueMeta() {
  const title = domainDisplayName(state.meta.domain);
  document.title = `${title} - exploration dashboard`;
  const h1 = document.getElementById("catalogue-title");
  if (h1) h1.textContent = title;
  const sub = document.getElementById("catalogue-subtitle");
  if (sub) {
    const nDocs = state.meta.n_linked_docs;
    const nTopics = state.meta.n_atoms;
    const docsText = Number.isFinite(nDocs) ? `${nDocs.toLocaleString()} linked documents` : "linked documents";
    const topicsText = Number.isFinite(nTopics) ? `${nTopics.toLocaleString()} topics` : "topics";
    sub.innerHTML =
      `Browse <strong>aspects</strong> and <strong>${topicsText}</strong>, ` +
      `open linked documents, and inspect highlighted evidence phrases. ` +
      `This run contains ${docsText}.`;
  }
}

async function loadCoreData() {
  const [manifest, docIndex, topicPhraseIndex] = await Promise.all([
    loadJson("data/manifest.json").catch(() => ({})),
    loadJson("data/doc_index.json").catch(() => ({})),
    loadJson("data/topic_phrase_index.json").catch(() => ({})),
  ]);
  state.manifest = manifest;
  state.docIndex = docIndex;
  state.topicPhraseIndex = topicPhraseIndex;
  state.sharded = Object.keys(state.docIndex).length > 0;
  const coreFiles = ["method_comparison.json", "aspects.jsonl", "nodes.jsonl",
    "atom_subclusters.jsonl", "facets_by_sub.jsonl", "llm_atom_names.jsonl",
    "llm_atom_facets.jsonl", "llm_aspect_names.jsonl", "llm_aspect_facets.jsonl"];
  loadTotal = coreFiles.reduce((s, fn) => s + ((state.manifest[fn] || []).length || 1), 0);
  loadDone = 0; loadTracking = true; renderLoadBar();
  const [meta, aspects, nodes, subs, facetsBySub,
         llmAtomNames, llmAtomFacets, llmAspectNames, llmAspectFacets] =
    await Promise.all([
      loadJson("data/method_comparison.json").catch(() => ({})),
      loadJsonl("data/aspects.jsonl"),
      loadJsonl("data/nodes.jsonl"),
      loadJsonl("data/atom_subclusters.jsonl"),
      loadJsonl("data/facets_by_sub.jsonl").catch(() => []),
      loadJsonl("data/llm_atom_names.jsonl").catch(() => []),
      loadJsonl("data/llm_atom_facets.jsonl").catch(() => []),
      loadJsonl("data/llm_aspect_names.jsonl").catch(() => []),
      loadJsonl("data/llm_aspect_facets.jsonl").catch(() => []),
    ]);
  loadTracking = false;
  state.meta = meta || {};
  applyCatalogueMeta();

  // Facet specs: indexed by sub_id
  state.facetsBySub = new Map();
  for (const r of (facetsBySub || [])) state.facetsBySub.set(r.sub_id, r);
  // LLM-given names (atom-level + aspect-level)
  state.llmAtomName = new Map();
  for (const r of (llmAtomNames || [])) state.llmAtomName.set(r.atom_id, r);
  state.llmAtomFacets = new Map();
  for (const r of (llmAtomFacets || [])) state.llmAtomFacets.set(r.atom_id, r);
  state.llmAspectName = new Map();
  for (const r of (llmAspectNames || [])) state.llmAspectName.set(r.aspect_id, r);
  state.llmAspectFacets = new Map();
  for (const r of (llmAspectFacets || [])) state.llmAspectFacets.set(r.aspect_id, r);

  for (const n of nodes) state.topicById.set(n.atom_id, n);

  // Collapse the per-atom "Other" bins for display. The pipeline emits one
  // other_has_meaning / other_no_meaning node PER source atom, so the bottom
  // "Other" aspect ends up with hundreds of identically-named members. Fold
  // each kind into a single synthetic topic so the "Other" aspect shows exactly
  // one "Has Meaning" and one "No Clear Meaning" row. Display-only — the
  // underlying nodes/occurrences are untouched.
  collapseOtherBins(nodes, aspects);

  // Fold the two bottom "Other" top-level aspects (coassociation 'others' +
  // absorb_small_atoms 'other_small') into a single "Other" aspect with two
  // labelled mid-level groups. Display-only; runs on collapseOtherBins' output.
  mergeOtherAspects(nodes, aspects);

  // Viewer-level cleanup for duplicate sibling labels (e.g. several "Location"
  // leaf rows under the same Geographic Locations parent). This creates virtual
  // display topics while leaving the raw source atom ids available for evidence.
  applySiblingLabelMerges(aspects);

  // keep the logical order the backend wrote (aspect_id is assigned in that
  // order: aspect-00, aspect-01, ...). Do NOT re-sort by doc count.
  aspects.sort((a, b) => String(a.aspect_id).localeCompare(String(b.aspect_id)));
  state.aspects = aspects;
  for (const a of aspects) state.aspectById.set(a.aspect_id, a);

  // Every atom the left tree can actually reach. A node can exist in
  // nodes.jsonl and still belong to no aspect — the three-layer rebuild drops
  // the rebasket Other bins out of grouping and only re-injects the recyclable
  // one — and evidence for a topic the catalogue does not offer must not be
  // marked up in document text either.
  state.catalogueAtomIds = new Set();
  for (const a of aspects) {
    for (const id of (a.member_atom_ids || [])) state.catalogueAtomIds.add(id);
    const tree = a.tree || {};
    for (const id of (tree.roots || [])) state.catalogueAtomIds.add(id);
    for (const kids of Object.values(tree.children_by_parent || {})) {
      for (const id of (kids || [])) state.catalogueAtomIds.add(id);
    }
  }

  // all aspects start collapsed; the user expands what they want.

  for (const s of subs) state.subByAtom.set(s.atom_id, s);

  // build phrase -> [{atom_id, sub_id, display_title, atom_title}] index
  // for click-to-jump highlighting in document detail.
  state.phraseToLocations = new Map();
  function indexPhrase(phr, atomId, subId, subTitle) {
    const key = (phr || "").toLowerCase().trim();
    if (!key) return;
    const displayAtomId = remapAtomIdForDisplay(atomId);
    const remapped = displayAtomId !== atomId;
    const displaySubId = remapped ? null : subId;
    const displaySubTitle = remapped ? null : subTitle;
    let arr = state.phraseToLocations.get(key);
    if (!arr) { arr = []; state.phraseToLocations.set(key, arr); }
    // dedupe by (atom_id, sub_id)
    if (arr.some(x => x.atom_id === displayAtomId && x.sub_id === displaySubId)) return;
    arr.push({ atom_id: displayAtomId, sub_id: displaySubId, sub_title: displaySubTitle, phrase_text: phr });
  }
  for (const s of subs) {
    if (s.indivisible) {
      // index the topic-level rep phrases so click-to-jump still works
      const t = state.topicById.get(s.atom_id);
      for (const ph of (t?.representative_phrases || [])) {
        indexPhrase(ph, s.atom_id, null, null);
      }
      continue;
    }
    for (const sc of (s.sub_clusters || [])) {
      for (const ph of (sc.all_phrases || [])) {
        indexPhrase(ph, s.atom_id, sc.sub_id, sc.display_title);
      }
    }
  }

  console.log(
    `loaded ${aspects.length} aspects, ${nodes.length} topics, ` +
    `${subs.length} atom sub-cluster records, ` +
    `${state.phraseToLocations.size} indexed phrases, ` +
    `${state.facetsBySub.size} facet specs`
  );
}

function refreshCurrentViews() {
  if (state.selectedTopicId) renderTopicDetail();
  if (state.selectedCombineA && state.selectedCombineB) renderCombine();
}

async function loadDeferredData() {
  if (state.sharded) { state.deferredStatus = ""; return; }
  try {
    state.deferredStatus = "Loading document text in the background...";
    const docs = await loadJsonl("data/documents.jsonl");
    state.docs = new Map();
    for (const d of docs) state.docs.set(d.doc_id, d);
    state.docsReady = true;
    console.log(`loaded ${docs.length} documents`);
    refreshCurrentViews();
  } catch (e) {
    state.deferredStatus = `Document text failed to load: ${e.message}`;
    console.error(e);
    refreshCurrentViews();
    return;
  }

  try {
    state.deferredStatus = "Loading phrase positions in the background...";
    const docPhrases = await loadJsonl("data/doc_all_phrases.jsonl");
    state.docAllPhrases = new Map();
    for (const r of docPhrases) state.docAllPhrases.set(r.doc_id, r.phrases);
    state.docPhrasesReady = true;
    state.deferredStatus = "Document text and phrase positions loaded.";
    console.log(`loaded phrase positions for ${docPhrases.length} documents`);
    refreshCurrentViews();
  } catch (e) {
    state.deferredStatus = `Phrase positions failed to load: ${e.message}`;
    console.error(e);
    refreshCurrentViews();
  }
}

