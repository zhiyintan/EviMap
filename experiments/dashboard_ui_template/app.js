// find sentence boundaries surrounding an offset: returns [s, e]
function sentenceBoundsAt(text, offset) {
  if (!text) return [0, 0];
  let prev = 0;
  let position = 0;
  for (const char of text) {
    if (/[.!?\n]/.test(char)) {
      if (position < offset) prev = position + 1;
      else return [prev, position + 1];
    }
    position++;
  }
  return [prev, position];
}

// find co-occurring (A, B) phrase pairs in a doc within window;
// window: -1 = whole doc; 0 = same sentence; >0 = within N chars
function findCooccurrences(occA, occB, docText, windowChars) {
  const pairs = [];
  for (const a of occA) {
    if (!Number.isInteger(a.start)) continue;
    const aMid = (a.start + (a.end || a.start)) / 2;
    let aBounds = null;
    if (windowChars === 0) aBounds = sentenceBoundsAt(docText, a.start);
    for (const b of occB) {
      if (!Number.isInteger(b.start)) continue;
      const bMid = (b.start + (b.end || b.start)) / 2;
      let inWindow = false;
      if (windowChars === -1) {
        inWindow = true;
      } else if (windowChars === 0) {
        // same sentence: b's start within aBounds
        inWindow = b.start >= aBounds[0] && b.start < aBounds[1];
      } else {
        inWindow = Math.abs(aMid - bMid) <= windowChars;
      }
      if (inWindow) pairs.push({ a, b, dist: Math.abs(aMid - bMid) });
    }
  }
  return pairs;
}

function renderCombine() {
  const list = document.getElementById("combine-doc-list");
  const subEl = document.getElementById("combine-sub");
  const detail = document.getElementById("combine-doc-detail");
  list.innerHTML = "";

  const selA = resolveCombineSel(state.selectedCombineA);
  const selB = resolveCombineSel(state.selectedCombineB);
  if (!selA || !selB) {
    subEl.textContent = "Pick two sides.";
    detail.innerHTML = `<p class="hint">Pick two sides, then click a document.</p>`;
    return;
  }
  if (state.selectedCombineA === state.selectedCombineB) {
    subEl.textContent = "Pick two different sides.";
    detail.innerHTML = "";
    return;
  }

  // doc sets: union of each side's atoms' support docs; intersection = "both discussed"
  const docsA = combineSelDocs(selA);
  const docsB = combineSelDocs(selB);
  const both = [];
  for (const d of docsA) if (docsB.has(d)) both.push(d);
  both.sort();

  // statistics line. The "N documents" count is wrapped so the guide can
  // spotlight just the number, not the whole sentence.
  subEl.innerHTML =
    `<span id="combine-count"><strong>${both.length}</strong> document${both.length === 1 ? "" : "s"}</span> discuss both ` +
    `<em>${escapeHtml(selA.label)}</em> (${docsA.size}) and <em>${escapeHtml(selB.label)}</em> (${docsB.size}).`;

  if (both.length === 0) {
    detail.innerHTML = `<p class="hint">No document discusses both. Try broader sides (a whole aspect).</p>`;
    return;
  }

  // rank: docs where both sides have more phrase hits first (when positions ready)
  const ranked = [];
  for (const docId of both) {
    let nA = null, nB = null;
    if (state.docPhrasesReady) {
      const occAll = state.docAllPhrases?.get(docId) || [];
      nA = occAll.filter(o => selA.atomIds.has(remapAtomIdForDisplay(o.atom_id))).length;
      nB = occAll.filter(o => selB.atomIds.has(remapAtomIdForDisplay(o.atom_id))).length;
    }
    ranked.push({ docId, nA, nB });
  }
  ranked.sort((x, y) => {
    if (state.docPhrasesReady) {
      return (Math.min(y.nA, y.nB) - Math.min(x.nA, x.nB)) ||
             ((y.nA + y.nB) - (x.nA + x.nB)) || x.docId.localeCompare(y.docId);
    }
    return x.docId.localeCompare(y.docId);
  });

  const shown = ranked.slice(0, 1000);
  for (const r of shown) {
    const li = document.createElement("li");
    li.dataset.docId = r.docId;
    if (r.docId === state.selectedCombineDoc) li.classList.add("selected");
    const meta = state.docPhrasesReady
      ? `${r.nA} + ${r.nB} key phrase${(r.nA + r.nB) === 1 ? "" : "s"}`
      : "phrase positions loading";
    li.innerHTML = `
      <span class="doc-id">${escapeHtml(r.docId)}</span>
      <span class="doc-evidence-meta">${escapeHtml(meta)}</span>
    `;
    li.addEventListener("click", async () => {
      await ensureDocBundle(r.docId);
      state.selectedCombineDoc = r.docId;
      renderCombine();
      notifyGuideInteraction("combine-doc-row");
    });
    list.appendChild(li);
  }
  if (shown.length < ranked.length) {
    const li = document.createElement("li");
    li.className = "doc-loading";
    li.textContent = `Showing first ${shown.length.toLocaleString()} of ${ranked.length.toLocaleString()}.`;
    list.appendChild(li);
  }

  if (state.selectedCombineDoc && both.includes(state.selectedCombineDoc)) {
    renderCombineDocBody(selA, selB, state.selectedCombineDoc);
  } else {
    detail.innerHTML = `<p class="hint">Click a document to see both sides highlighted in the text.</p>`;
  }
}

function renderCombineDocBody(selA, selB, docId) {
  const detail = document.getElementById("combine-doc-detail");
  const doc = state.docs.get(docId);
  if (!doc) {
    detail.innerHTML = `<p class="hint">${escapeHtml(state.deferredStatus || "Document text is still loading.")}</p>`;
    return;
  }
  if (!state.docPhrasesReady && !state.sharded) {
    detail.innerHTML = `
      <div class="doc-text-header">
        <h2>${escapeHtml(docId)}</h2>
        <p class="hint">${escapeHtml(state.deferredStatus)} Co-occurrence highlighting will appear when phrase positions finish loading.</p>
      </div>
      <div class="doc-body">${escapeHtml(doc.text)}</div>
    `;
    return;
  }
  const occAll = state.docAllPhrases?.get(docId) || [];
  // Match (and later jump) on the REMAPPED id so synthetic Other topics and
  // viewer-level sibling merges still resolve to their member occurrences and
  // land in the left tree — same reason as the Browse-tab gray-phrase jump.
  const occId = (o) => remapAtomIdForDisplay(o.atom_id);
  const occA = occAll.filter(o => selA.atomIds.has(occId(o)));
  const occB = occAll.filter(o => selB.atomIds.has(occId(o)));

  // mark A phrases as combine-a, B phrases as combine-b
  const mk = (cls) => (o) => ({ ...o, cssClass: cls,
                                jumpAtom: occId(o),
                                jumpSub: occId(o) !== o.atom_id ? null : o.sub_id });
  const phrases = []
    .concat(occA.map(mk("combine-a")))
    .concat(occB.map(mk("combine-b")));
  const { html, fallback } = buildHighlightedHtml(doc.text, phrases);

  // distinct surface phrases each side contributes in this doc (the "fragments"
  // that show how both topics are discussed here)
  const uniq = (occs) => {
    const seen = new Set(); const out = [];
    for (const o of occs) {
      const k = (o.text || "").toLowerCase().trim();
      if (k && !seen.has(k)) { seen.add(k); out.push(o.text); }
    }
    return out;
  };
  const phrasesA = uniq(occA), phrasesB = uniq(occB);
  const sideFragments = (label, cls, list) => list.length ? `
      <div class="cooc-side">
        <span class="legend-chip ${cls}">${escapeHtml(label)}</span>
        ${list.slice(0, 15).map(p => `<span class="phrase-chip">${escapeHtml(p)}</span>`).join(" ")}
        ${list.length > 15 ? `<span class="more">+${list.length - 15}</span>` : ""}
      </div>` : "";

  let fallbackHtml = "";
  if (fallback.length) {
    fallbackHtml = `
      <details class="unrecovered-phrases">
        <summary>${fallback.length} phrase${fallback.length === 1 ? "" : "s"} not located in text</summary>
        <div class="unrecovered-list">
          ${fallback.map(p => `<span class="phrase-chip">${escapeHtml(p.text)}</span>`).join(" ")}
        </div>
      </details>
    `;
  }

  detail.innerHTML = `
    <div class="doc-text-header">
      <h2>${escapeHtml(docId)}</h2>
      <div class="legend">
        <span class="legend-chip combine-a">${escapeHtml(selA.label)}</span>
        <span class="legend-chip combine-b">${escapeHtml(selB.label)}</span>
        <span>${phrasesA.length} + ${phrasesB.length} key phrase${(phrasesA.length + phrasesB.length) === 1 ? "" : "s"} here</span>
      </div>
    </div>
    <div class="cooc-summary">
      ${sideFragments(selA.label, "combine-a", phrasesA)}
      ${sideFragments(selB.label, "combine-b", phrasesB)}
    </div>
    ${fallbackHtml}
    <div class="doc-body">${html}</div>
  `;
  // wire jump
  detail.querySelectorAll("mark.jump").forEach(m => {
    m.addEventListener("click", (ev) => {
      ev.stopPropagation();
      const aid = m.getAttribute("data-jump-atom");
      const sid = m.getAttribute("data-jump-sub");
      if (!aid) return;
      // switch to Browse Aspects tab and jump there
      document.querySelector('.tab[data-tab="browse"]').click();
      jumpToLocation({ atom_id: aid, sub_id: sid || null });
      notifyGuideInteraction("linked-phrase");
    });
  });
  scrollDocDetailToFirstPhrase(detail, "mark.combine-a, mark.combine-b");
}

