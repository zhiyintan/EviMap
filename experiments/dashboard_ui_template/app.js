function renderAspectTree() {
  const root = document.getElementById("aspect-tree");
  root.innerHTML = "";
  const filterStr = (
    document.getElementById("aspect-filter").value || ""
  ).toLowerCase().trim();

  for (const aspect of state.aspects) {
    const aspectMembers = aspect.member_atom_ids
      .map(id => state.topicById.get(id))
      .filter(Boolean);

    // filter visibility: show aspect if title or any topic matches
    let aspectVisible = true;
    if (filterStr) {
      const blob = aspectSearchBlob(aspect);
      aspectVisible = blob.includes(filterStr);
    }
    if (!aspectVisible) continue;

    const isExpanded = state.expandedAspects.has(aspect.aspect_id) || filterStr;

    // header
    const header = document.createElement("div");
    header.className = "aspect-header";
    header.dataset.aspectId = aspect.aspect_id;
    if (isExpanded) header.classList.add("expanded");
    header.innerHTML = `
      <span class="aspect-caret">${isExpanded ? "▾" : "▸"}</span>
      <span class="aspect-title">${escapeHtml(aspectLabel(aspect))}</span>
      <span class="aspect-meta">
        ${aspect.n_atoms} topic${aspect.n_atoms === 1 ? "" : "s"}
        · ${aspect.n_documents_total} docs
      </span>
    `;
    header.addEventListener("click", () => {
      // During the guide's aspect step, the click should only ADVANCE the tour —
      // the next step plays its own scroll-then-expand animation, so don't toggle
      // here (toggling would expand-then-collapse and flicker).
      if (window.__evimapGuideSuppressAspectToggle) {
        notifyGuideInteraction("aspect-header");
        return;
      }
      if (state.expandedAspects.has(aspect.aspect_id)) {
        state.expandedAspects.delete(aspect.aspect_id);
      } else {
        state.expandedAspects.add(aspect.aspect_id);
      }
      renderAspectTree();
      notifyGuideInteraction("aspect-header");
    });
    root.appendChild(header);

    if (!isExpanded) continue;

    // body — render topics either as tree or flat list
    const tree = aspect.tree || {};
    const childrenByParent = tree.children_by_parent || {};
    const roots = tree.roots || [];
    const rendered = new Set();

    const body = document.createElement("ul");
    body.className = "topic-list";

    // recursive renderer for tree
    function renderTopic(atomId, depth) {
      if (rendered.has(atomId)) return;
      rendered.add(atomId);
      const t = state.topicById.get(atomId);
      if (!t) return;
      const sub = state.subByAtom.get(atomId);
      const hasSplittable = sub && !sub.indivisible && (sub.sub_clusters || []).length > 1;
      const subOpen = state.expandedTopics.has(atomId);

      // A mid-level "group header" node (from 3-layer co-association): it is a
      // collapsible folder over its atom children — clicking it expands/collapses
      // the children, it does NOT open documents.
      const isGroupHeader = !!t.is_group_header;
      const groupChildren = childrenByParent[atomId] || [];
      const groupOpen = state.expandedTopics.has(atomId);

      const li = document.createElement("li");
      li.className = "topic-row" + (isGroupHeader ? " group-header-row" : "");
      li.dataset.atomId = atomId;
      if (t.atom_id === state.selectedTopicId && !state.selectedSubId) {
        li.classList.add("selected");
      }
      li.style.paddingLeft = (16 + depth * 18) + "px";
      let caret;
      if (isGroupHeader && groupChildren.length) {
        caret = `<span class="sub-caret" data-group-toggle="${atomId}">${groupOpen ? "▾" : "▸"}</span>`;
      } else if (hasSplittable) {
        caret = `<span class="sub-caret" data-sub-toggle="${atomId}">${subOpen ? "▾" : "▸"}</span>`;
      } else {
        caret = `<span class="sub-caret-placeholder"></span>`;
      }
      const treeIcon = (!isGroupHeader && groupChildren.length)
                          ? `<span class="topic-tree-icon">└</span>` : "";
      const mergeBadge = t.is_virtual_sibling_merge
        ? `<span class="topic-merge-badge" title="Merged from ${t._collapsed_from || 0} sibling topics with the same label">${t._collapsed_from || 0}</span>`
        : "";
      li.innerHTML = `
        ${treeIcon}${caret}<span class="topic-name">${escapeHtml(topicLabel(t))}${mergeBadge}</span>
        <span class="topic-doc-count">${t.support_doc_count}</span>
      `;
      li.addEventListener("click", (ev) => {
        // sub-cluster caret toggles sub expansion
        if (ev.target.dataset && ev.target.dataset.subToggle) {
          ev.stopPropagation();
          if (state.expandedTopics.has(atomId)) state.expandedTopics.delete(atomId);
          else state.expandedTopics.add(atomId);
          renderAspectTree();
          return;
        }
        // group-header click (anywhere on the row) toggles its children
        if (isGroupHeader) {
          ev.stopPropagation();
          if (state.expandedTopics.has(atomId)) state.expandedTopics.delete(atomId);
          else state.expandedTopics.add(atomId);
          renderAspectTree();
          return;
        }
        ev.stopPropagation();
        state.selectedTopicId = t.atom_id;
        state.selectedSubId = null;
        state.selectedDocId = null;
        state.selectedPhrases.clear();
        renderAspectTree();
        renderTopicDetail();
        notifyGuideInteraction("topic-row");
        // NOTE: do NOT prefetch topic phrases on topic-open. For large corpora one
        // topic-phrase shard can be ~18 MiB (eu_debates); pulling it here saturates
        // the connection so opening a topic / document stalls (and big files fail
        // with ERR_CONNECTION_FAILED on flaky / cold-cache networks). It loads
        // lazily only when the user clicks a phrase chip to filter.
      });
      body.appendChild(li);

      // sub-cluster list (if expanded)
      if (hasSplittable && subOpen) {
        const subList = sub.sub_clusters.slice();
        const conf = sub.split_confidence || "low";
        for (const sc of subList) {
          const facetSpec = state.facetsBySub?.get(sc.sub_id);
          const hasFacets = facetSpec && (facetSpec.facets || []).length > 0;

          const subLi = document.createElement("li");
          subLi.className = "sub-row";
          subLi.dataset.subId = sc.sub_id;
          if (state.selectedSubId === sc.sub_id) {
            subLi.classList.add("selected");
          }
          subLi.style.paddingLeft = (16 + depth * 18 + 28) + "px";
          // when facets are available, prefer the LLM aspect_summary
          // as the visible name (still mark old centroid title)
          const visibleName = hasFacets
                                ? escapeHtml(facetSpec.aspect_summary || sc.display_title)
                                : escapeHtml(sc.display_title);
          const facetBadge = hasFacets
              ? `<span class="facet-badge" title="${facetSpec.facets.length} facets">⊞ ${facetSpec.facets.length}</span>`
              : "";
          subLi.innerHTML = `
            <span class="sub-caret-placeholder"></span><span class="sub-name" title="${escapeHtml((sc.representative_phrases || []).slice(0, 5).join(', '))}">${visibleName}</span>
            ${facetBadge}
            <span class="sub-confidence sub-confidence-${conf}">${conf}</span>
            <span class="topic-doc-count">${sc.support_doc_count}</span>
          `;
          subLi.addEventListener("click", (ev) => {
            ev.stopPropagation();
            state.selectedTopicId = t.atom_id;
            state.selectedSubId = sc.sub_id;
            state.selectedLlmNodeId = null;
            state.selectedDocId = null;
            state.selectedPhrases.clear();
            // reset facet filter when switching subs
            renderAspectTree();
            renderTopicDetail();
          });
          body.appendChild(subLi);
        }
      }

      // children: a group header reveals its children only when expanded;
      // ordinary tree nodes keep showing their children inline.
      if (!isGroupHeader || groupOpen) {
        for (const childId of groupChildren) {
          renderTopic(childId, depth + 1);
        }
      }
    }

    // render the mid-group "roots" in the logical order the backend wrote
    // (tree.roots is already ordered by the LLM; do NOT re-sort by support).
    for (const r of roots) renderTopic(r, 0);
    // then any remaining members (not in tree, not yet rendered), file order
    // Catch members the tree walk missed. A node that HAS a parent is not
    // missing, it is just inside a collapsed folder — emitting it here would
    // render it at depth 0 beside its own folder and defeat the collapse.
    const hasParent = new Set();
    for (const kids of Object.values(childrenByParent)) {
      for (const k of (kids || [])) hasParent.add(k);
    }
    const remaining = aspect.member_atom_ids.filter(
      id => !rendered.has(id) && !hasParent.has(id));
    for (const id of remaining) renderTopic(id, 0);

    root.appendChild(body);
  }
}

function findSubCluster(atomId, subId) {
  if (!subId) return null;
  const rec = state.subByAtom.get(atomId);
  if (!rec || !rec.sub_clusters) return null;
  return rec.sub_clusters.find(sc => sc.sub_id === subId) || null;
}

function renderFacetFilter(host, facetSpec, facetSel, onChange) {
  // host = the .related-phrases container; we replace its layout
  host.innerHTML = "";
  host.classList.add("facet-filter");
  for (const f of facetSpec.facets) {
    const row = document.createElement("div");
    row.className = "facet-row";
    const labelKind = f.facet_kind === "attribute" ? "attribute" : "subject";
    row.innerHTML = `
      <div class="facet-label">
        <span class="facet-name">${escapeHtml(f.facet_name || '?')}</span>
        <span class="facet-kind facet-kind-${labelKind}">${labelKind}</span>
      </div>
    `;
    const chipBox = document.createElement("div");
    chipBox.className = "facet-chips";
    for (const v of f.values) {
      const chip = document.createElement("button");
      chip.className = "facet-chip";
      const isOn = facetSel?.get(f.facet_id)?.has(v.value_label);
      if (isOn) chip.classList.add("on");
      chip.innerHTML = `${escapeHtml(v.value_label)} <span class="facet-chip-count">${v.support_doc_count}</span>`;
      chip.title = (v.phrase_texts || []).slice(0, 6).join(", ");
      chip.addEventListener("click", () => {
        if (!facetSel.has(f.facet_id)) facetSel.set(f.facet_id, new Set());
        const set = facetSel.get(f.facet_id);
        if (set.has(v.value_label)) set.delete(v.value_label);
        else set.add(v.value_label);
        // clear selected doc when filter changes
        state.selectedDocId = null;
        onChange();
      });
      chipBox.appendChild(chip);
    }
    row.appendChild(chipBox);
    host.appendChild(row);
  }
  // clear-all button if anything selected
  const hasAny = Array.from(facetSel.values()).some(s => s && s.size > 0);
  if (hasAny) {
    const clear = document.createElement("button");
    clear.className = "facet-clear";
    clear.textContent = "clear all filters";
    clear.addEventListener("click", () => {
      for (const set of facetSel.values()) set.clear();
      state.selectedDocId = null;
      onChange();
    });
    host.appendChild(clear);
  }
}

