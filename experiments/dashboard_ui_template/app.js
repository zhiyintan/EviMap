function normalizeSiblingLabel(s) {
  return String(s ?? "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function stableHash(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0).toString(36);
}

function uniqueStable(values, limit = Infinity) {
  const seen = new Set();
  const out = [];
  for (const v of values || []) {
    const key = typeof v === "string" ? v.toLowerCase().trim() : String(v);
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(v);
    if (out.length >= limit) break;
  }
  return out;
}

function collectSiblingMergeNode(virtualId, label, memberIds) {
  const members = memberIds
    .map(id => state.topicById.get(id))
    .filter(Boolean);
  const base = members.slice().sort(
    (a, b) => (b.support_doc_count || 0) - (a.support_doc_count || 0)
  )[0];
  const docIds = new Set();
  const reps = [];
  const entryIds = [];
  const typeIds = [];
  for (const n of members) {
    for (const d of (n.support_doc_ids || [])) docIds.add(d);
    for (const p of (n.representative_phrases || [])) reps.push(p);
    for (const id of (n.member_phrase_entry_ids || [])) entryIds.push(id);
    for (const id of (n.member_phrase_type_ids || [])) typeIds.push(id);
  }
  return {
    ...(base || {}),
    atom_id: virtualId,
    display_title: label,
    centroid_title: label,
    representative_phrases: uniqueStable(reps, 20),
    support_doc_ids: Array.from(docIds).sort(),
    support_doc_count: docIds.size,
    member_phrase_entry_ids: Array.from(new Set(entryIds)).sort((a, b) => a - b),
    member_phrase_type_ids: Array.from(new Set(typeIds)).sort((a, b) => a - b),
    n_member_entries: new Set(entryIds).size,
    n_member_types: new Set(typeIds).size,
    is_virtual_sibling_merge: true,
    merged_from_atoms: memberIds.slice(),
    _collapsed_from: memberIds.length,
  };
}

function applySiblingLabelMerges(aspects) {
  // Viewer-level cleanup: within the SAME parent, fold leaf topics whose final
  // display labels are exactly identical after light normalization. This catches
  // cases like six sibling "Location" rows without changing the source data.
  state.siblingIdRemap = new Map();
  state.virtualTopicMembers = new Map();
  state.hiddenTopicIds = new Set();
  let nGroups = 0;
  let nHidden = 0;

  function isLeafTopic(id, childrenByParent) {
    const t = state.topicById.get(id);
    return !!t && !t.is_group_header && !(childrenByParent[id] || []).length;
  }

  function rewriteSiblingList(ids, aspect, parentId, childrenByParent) {
    const buckets = new Map();
    for (const id of ids) {
      if (!isLeafTopic(id, childrenByParent)) continue;
      const t = state.topicById.get(id);
      const key = normalizeSiblingLabel(topicLabel(t));
      if (!key || key.startsWith("other ")) continue;
      if (!buckets.has(key)) buckets.set(key, []);
      buckets.get(key).push(id);
    }
    const mergeByFirstId = new Map();
    const hidden = new Set();
    for (const [key, memberIds] of buckets) {
      if (memberIds.length < 2) continue;
      const label = topicLabel(state.topicById.get(memberIds[0]));
      const virtualId = `virtual::sibling::${aspect.aspect_id}::${stableHash(`${parentId || "root"}|${key}`)}`;
      const virtualNode = collectSiblingMergeNode(virtualId, label, memberIds);
      state.topicById.set(virtualId, virtualNode);
      state.virtualTopicMembers.set(virtualId, memberIds.slice());
      for (const mid of memberIds) {
        state.siblingIdRemap.set(mid, virtualId);
        state.hiddenTopicIds.add(mid);
        hidden.add(mid);
      }
      mergeByFirstId.set(memberIds[0], virtualId);
      nGroups += 1;
      nHidden += memberIds.length - 1;
    }
    if (!mergeByFirstId.size) return ids;
    const out = [];
    const seen = new Set();
    for (const id of ids) {
      const repl = mergeByFirstId.get(id);
      if (repl) {
        if (!seen.has(repl)) { seen.add(repl); out.push(repl); }
        continue;
      }
      if (hidden.has(id)) continue;
      if (!seen.has(id)) { seen.add(id); out.push(id); }
    }
    return out;
  }

  for (const aspect of aspects) {
    const tree = aspect.tree || {};
    const childrenByParent = tree.children_by_parent || {};
    let reduced = 0;
    for (const [parentId, kids] of Object.entries(childrenByParent)) {
      const nextKids = rewriteSiblingList(kids || [], aspect, parentId, childrenByParent);
      reduced += (kids || []).length - nextKids.length;
      childrenByParent[parentId] = nextKids;
    }
    if (Array.isArray(tree.roots)) {
      const nextRoots = rewriteSiblingList(tree.roots, aspect, "", childrenByParent);
      reduced += tree.roots.length - nextRoots.length;
      tree.roots = nextRoots;
    }
    if (Array.isArray(aspect.member_atom_ids)) {
      const seenMembers = new Set();
      const nextMembers = [];
      for (const id of aspect.member_atom_ids) {
        const repl = state.siblingIdRemap.get(id) || id;
        if (state.hiddenTopicIds.has(id) && repl === id) continue;
        if (seenMembers.has(repl)) continue;
        seenMembers.add(repl);
        nextMembers.push(repl);
      }
      aspect.member_atom_ids = nextMembers;
    }
    if (reduced > 0) {
      aspect.n_atoms = Math.max(0, (aspect.n_atoms || 0) - reduced);
      const edges = [];
      for (const [parent, kids] of Object.entries(childrenByParent)) {
        for (const child of (kids || [])) edges.push({ parent, child });
      }
      tree.edges = edges;
      tree.n_edges = edges.length;
    }
  }
  if (nGroups) {
    console.log(`[siblingLabelMerge] folded ${nGroups} duplicate sibling-label groups, hiding ${nHidden} duplicate rows`);
  }
}

function normText(s) {
  return String(s ?? "").toLowerCase().trim();
}

function topicSearchBlob(topic) {
  const sub = state.subByAtom.get(topic.atom_id);
  const parts = [
    topicLabel(topic),
    topic.display_title,
    topic.centroid_title,
    ...(topic.representative_phrases || []),
  ];
  for (const sc of (sub?.sub_clusters || [])) {
    parts.push(sc.display_title, ...(sc.representative_phrases || []), ...(sc.all_phrases || []));
  }
  return normText(parts.filter(Boolean).join(" "));
}

function aspectSearchBlob(aspect) {
  const parts = [
    aspectLabel(aspect),
    aspect.aspect_title,
    aspect.aspect_key,
  ];
  for (const atomId of (aspect.member_atom_ids || [])) {
    const t = state.topicById.get(atomId);
    if (t) parts.push(topicSearchBlob(t));
  }
  return normText(parts.filter(Boolean).join(" "));
}

function orderLlmNodes(nodes) {
  // depth-first: roots, then their children, recursively, sorted by support
  const byParent = new Map();
  for (const n of nodes) {
    const p = n.parent_temp_node_id || "__root__";
    if (!byParent.has(p)) byParent.set(p, []);
    byParent.get(p).push(n);
  }
  for (const arr of byParent.values()) {
    arr.sort((a, b) => (b.support_doc_count || 0) - (a.support_doc_count || 0));
  }
  const out = [];
  function walk(parentKey) {
    for (const n of (byParent.get(parentKey) || [])) {
      out.push(n);
      walk(n.temp_node_id);
    }
  }
  walk("__root__");
  return out;
}

function buildSearchResults(query) {
  const q = normText(query);
  if (!q) return { aspects: [], atoms: [], phrases: [] };

  const aspects = [];
  for (const aspect of state.aspects) {
    if (!aspectSearchBlob(aspect).includes(q)) continue;
    const matchingTopics = (aspect.member_atom_ids || []).filter(atomId => {
      const t = state.topicById.get(atomId);
      return t && topicSearchBlob(t).includes(q);
    });
    aspects.push({ aspect, matchingTopics });
  }

  const atoms = [];
  for (const topic of state.topicById.values()) {
    if (state.hiddenTopicIds?.has(topic.atom_id)) continue;
    if (!topicSearchBlob(topic).includes(q)) continue;
    atoms.push(topic);
  }
  atoms.sort((a, b) => (b.support_doc_count || 0) - (a.support_doc_count || 0));

  const phrases = [];
  for (const [key, locs] of state.phraseToLocations.entries()) {
    if (!key.includes(q)) continue;
    phrases.push({
      key,
      text: locs[0]?.phrase_text || key,
      locations: locs,
    });
  }
  phrases.sort((a, b) =>
    (b.locations.length - a.locations.length) || a.key.localeCompare(b.key));

  return {
    aspects: aspects.slice(0, 6),
    atoms: atoms.slice(0, 8),
    phrases: phrases.slice(0, 12),
  };
}

