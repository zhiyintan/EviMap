  // Step 3 -> 4 staged reveal:
  //   1. the step-3 note disappears (panel hidden), the aspect stays yellow + boxed;
  //   2. the aspect expands down to the leaf (group + leaf appear below it);
  //   3. the tree SLOWLY scrolls so the whole aspect->group->leaf path sits near the
  //      TOP of the column (not buried at the bottom under the note), box following;
  //   4. the step-4 note appears.
  async function guideScrollAspectThenExpand(aspectFn, expandFn, pathFn) {
    const myToken = guideRenderToken;            // bail if a newer render takes over
    const alive = () => guideActive && !modal.hidden && guideRenderToken === myToken;
    const tree = document.getElementById("aspect-tree");
    // (1) hide the step-3 note; keep the aspect yellow + box on it.
    if (panel) panel.style.visibility = "hidden";
    guidePinAspectHighlight(aspectFn, false);
    await new Promise(r => window.requestAnimationFrame(r));
    if (!alive()) return;
    // (2) expand the path so the group + leaf exist in the DOM (do this BEFORE the
    //     scroll so we can scroll the full expanded path to the top).
    expandFn();
    await new Promise(r => window.requestAnimationFrame(r));
    if (!alive()) return;
    guidePinAspectHighlight(aspectFn, false);    // re-apply yellow to the new header
    await guidePause(140);                        // brief beat: "it expanded"
    if (!alive()) return;
    // (3) slow-scroll the whole path to the top of the column, box following.
    if (tree) {
      const from = tree.scrollTop;
      const want = computeTreeScrollTopAtTop(pathFn());
      if (want != null && Math.abs(want - from) > 1) {
        const dur = 620;                          // slow, deliberate scroll
        const start = await new Promise(r => window.requestAnimationFrame(r));
        for (;;) {
          const now = await new Promise(r => window.requestAnimationFrame(r));
          if (!alive()) return;
          const k = Math.min(1, (now - start) / dur);
          const eased = k < 0.5 ? 2 * k * k : 1 - Math.pow(-2 * k + 2, 2) / 2;  // easeInOutQuad
          tree.scrollTop = from + (want - from) * eased;
          guidePinAspectHighlight(aspectFn, false);   // aspect stays yellow, box follows
          if (k >= 1) break;
        }
      }
      await guidePause(120);
      if (!alive()) return;
    }
    // (4) reveal the step-4 note; renderGuideStep then frames the full path.
    if (panel) panel.style.visibility = "";
  }

