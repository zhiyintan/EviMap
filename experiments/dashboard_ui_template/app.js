// Resolve a combine selection value ("aspect:<id>", "group:<gid>", or
// "atom:<aid>") into the set of atom_ids it covers and a display label.
// Aspect = all atoms under all its mid-groups; group = atoms directly under
// that mid-group; atom = that one atom. Returns null for an unknown value.
// (Combine-only; does not touch the Browse tab.)
function resolveCombineSel(value) {
  if (!value) return null;
  if (value.startsWith("atom:")) {
    const aid = value.slice(5);
    const t = state.topicById.get(aid);
    if (!t) return null;
    return { label: topicLabel(t), atomIds: new Set([aid]) };
  }
  if (value.startsWith("aspect:")) {
    const aid = value.slice(7);
    const asp = state.aspectById.get(aid);
    if (!asp) return null;
    const cbp = asp.tree?.children_by_parent || {};
    const atoms = new Set();
    for (const g of (asp.tree?.roots || [])) {
      for (const at of (cbp[g] || [])) atoms.add(at);
    }
    return { label: asp.aspect_title, atomIds: atoms };
  }
  if (value.startsWith("group:")) {
    const gid = value.slice(6);
    // find which aspect owns this group, read its atoms from children_by_parent
    for (const asp of state.aspects) {
      const cbp = asp.tree?.children_by_parent || {};
      if (cbp[gid]) {
        const gnode = state.topicById.get(gid);
        const label = gnode?.display_title || gid;
        return { label, atomIds: new Set(cbp[gid]) };
      }
    }
    return null;
  }
  return null;
}

// docs covered by a resolved selection = union of its atoms' support_doc_ids
function combineSelDocs(sel) {
  const docs = new Set();
  if (!sel) return docs;
  for (const atomId of sel.atomIds) {
    const t = state.topicById.get(atomId);
    for (const d of (t?.support_doc_ids || [])) docs.add(d);
  }
  return docs;
}

