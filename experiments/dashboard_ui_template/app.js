  function scrollTreeToShowTargets(targets, behavior = "auto") {
    const tree = document.getElementById("aspect-tree");
    const visibleTargets = (targets || []).filter(Boolean);
    if (!tree || !visibleTargets.length) return null;
    const treeRect = tree.getBoundingClientRect();
    let top = Infinity;
    let bottom = -Infinity;
    for (const el of visibleTargets) {
      const rect = el.getBoundingClientRect();
      top = Math.min(top, rect.top - treeRect.top + tree.scrollTop);
      bottom = Math.max(bottom, rect.bottom - treeRect.top + tree.scrollTop);
    }
    if (!Number.isFinite(top) || !Number.isFinite(bottom)) return null;
    const margin = 18;
    const span = bottom - top;
    let nextTop;
    if (span <= tree.clientHeight - margin * 2) {
      nextTop = top - margin;
    } else {
      nextTop = Math.max(0, bottom - tree.clientHeight + margin);
    }
    nextTop = Math.max(0, nextTop);
    tree.scrollTo({ top: nextTop, behavior });
    return nextTop;
  }

