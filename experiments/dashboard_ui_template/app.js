function setupColumnResizers() {
  // Each .three-col grid is "L | resizer | M | resizer | R" with template
  // "<L>px 6px <M>px 6px 1fr". We adjust <L> and <M> by tracking mouse drag.
  document.querySelectorAll(".three-col").forEach(grid => {
    const resizers = grid.querySelectorAll(".col-resizer");
    if (resizers.length !== 2) return;
    function getCols() {
      const tpl = window.getComputedStyle(grid).gridTemplateColumns;
      // computed yields pixel values
      return tpl.split(" ").map(s => parseFloat(s));
    }
    function setCols(L, M) {
      grid.style.gridTemplateColumns = `${L}px 6px ${M}px 6px 1fr`;
    }
    resizers.forEach((r, idx) => {
      r.addEventListener("mousedown", (ev) => {
        ev.preventDefault();
        r.classList.add("dragging");
        const cols0 = getCols();  // [L, 6, M, 6, R]
        const startX = ev.clientX;
        const onMove = (ev2) => {
          const dx = ev2.clientX - startX;
          let L = cols0[0], M = cols0[2];
          if (idx === 0) {
            L = Math.max(120, Math.min(window.innerWidth - 400, cols0[0] + dx));
          } else {
            M = Math.max(120, Math.min(window.innerWidth - L - 200, cols0[2] + dx));
          }
          setCols(L, M);
        };
        const onUp = () => {
          r.classList.remove("dragging");
          window.removeEventListener("mousemove", onMove);
          window.removeEventListener("mouseup", onUp);
        };
        window.addEventListener("mousemove", onMove);
        window.addEventListener("mouseup", onUp);
      });
    });
  });
}

function setupTabs() {
  const views = {
    browse: document.getElementById("view-browse"),
    combine: document.getElementById("view-combine"),
    about: document.getElementById("view-about"),
  };
  function activate(tabName) {
    document.querySelectorAll(".tab").forEach(x => x.classList.remove("active"));
    const btn = document.querySelector(`.tab[data-tab="${tabName}"]`);
    if (btn) btn.classList.add("active");
    for (const [name, el] of Object.entries(views)) {
      if (!el) continue;
      el.hidden = (name !== tabName);
      // explicitly drive display so a stale `display` rule from CSS
      // can't leave the view invisible after `hidden=false`
      el.style.display = (name === tabName) ? "" : "none";
    }
  }
  // delegate clicks at the document level so re-rendering doesn't lose handlers
  document.addEventListener("click", (ev) => {
    const target = ev.target.closest(".tab");
    if (!target) return;
    const name = target.dataset.tab;
      if (name && views[name]) {
        activate(name);
        if (name === "combine") notifyGuideInteraction("combine-tab");
        if (name === "about") notifyGuideInteraction("about-tab");
      }
  });
  activate("browse");   // set initial visible view explicitly
}

